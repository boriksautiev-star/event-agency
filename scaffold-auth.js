write("auth/AuthContext.tsx", [
  'import { createContext, useContext, useEffect, useState, ReactNode } from "react";',
  'import { api, authStorage } from "../api/client";',
  '',
  'export type Role = "director" | "admin" | "animator";',
  '',
  'export type User = {',
  '  id: string;',
  '  role: Role;',
  '  firstName: string;',
  '  lastName: string;',
  '  phone: string;',
  '  email: string | null;',
  '  status: "active" | "blocked" | "invited";',
  '};',
  '',
  'type AuthContextValue = {',
  '  user: User | null;',
  '  loading: boolean;',
  '  login: (phone: string, password: string) => Promise<void>;',
  '  logout: () => void;',
  '};',
  '',
  'const AuthContext = createContext<AuthContextValue | null>(null);',
  '',
  'export function AuthProvider({ children }: { children: ReactNode }) {',
  '  const [user, setUser] = useState<User | null>(null);',
  '  const [loading, setLoading] = useState(true);',
  '',
  '  // Восстановление сессии при старте',
  '  useEffect(() => {',
  '    let cancelled = false;',
  '    (async () => {',
  '      if (!authStorage.getAccess()) {',
  '        setLoading(false);',
  '        return;',
  '      }',
  '      try {',
  '        const { data } = await api.get<{ user: User }>("/auth/me");',
  '        if (!cancelled) setUser(data.user);',
  '      } catch {',
  '        authStorage.clear();',
  '      } finally {',
  '        if (!cancelled) setLoading(false);',
  '      }',
  '    })();',
  '    return () => { cancelled = true; };',
  '  }, []);',
  '',
  '  // Реакция на принудительный logout из axios-интерсептора',
  '  useEffect(() => {',
  '    const onLogout = () => setUser(null);',
  '    window.addEventListener("auth:logout", onLogout);',
  '    return () => window.removeEventListener("auth:logout", onLogout);',
  '  }, []);',
  '',
  '  const login = async (phone: string, password: string) => {',
  '    const { data } = await api.post<{ user: User; accessToken: string; refreshToken: string }>(',
  '      "/auth/login",',
  '      { phone, password },',
  '    );',
  '    if (data.user.role !== "director" && data.user.role !== "admin") {',
  '      throw new Error("\u0414\u043E\u0441\u0442\u0443\u043F \u0442\u043E\u043B\u044C\u043A\u043E \u0434\u043B\u044F \u0434\u0438\u0440\u0435\u043A\u0442\u043E\u0440\u0430 \u0438 \u0430\u0434\u043C\u0438\u043D\u0430");',
  '    }',
  '    authStorage.setTokens(data.accessToken, data.refreshToken);',
  '    setUser(data.user);',
  '  };',
  '',
  '  const logout = () => {',
  '    authStorage.clear();',
  '    setUser(null);',
  '  };',
  '',
  '  return (',
  '    <AuthContext.Provider value={{ user, loading, login, logout }}>',
  '      {children}',
  '    </AuthContext.Provider>',
  '  );',
  '}',
  '',
  'export function useAuth() {',
  '  const ctx = useContext(AuthContext);',
  '  if (!ctx) throw new Error("useAuth \u0434\u043E\u043B\u0436\u0435\u043D \u0431\u044B\u0442\u044C \u0432\u043D\u0443\u0442\u0440\u0438 <AuthProvider>");',
  '  return ctx;',
  '}',
  '',
].join("\n"));

